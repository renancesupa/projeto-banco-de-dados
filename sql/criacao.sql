-- Esquema normalizado para os dados de barragens da ANA.
-- Equipe: Alexandre Arthur, Enrique Luis e Renan Gomes.
BEGIN;

CREATE TABLE uf (
    sigla TEXT NOT NULL,
    CONSTRAINT pk_uf PRIMARY KEY (sigla)
);

CREATE TABLE municipio (
    id_municipio INTEGER GENERATED BY DEFAULT AS IDENTITY,
    uf_sigla TEXT NOT NULL,
    nome TEXT NOT NULL,
    CONSTRAINT pk_municipio PRIMARY KEY (id_municipio),
    CONSTRAINT fk_municipio_uf FOREIGN KEY (uf_sigla)
        REFERENCES uf (sigla),
    CONSTRAINT uq_municipio_uf_nome UNIQUE (uf_sigla, nome)
);

CREATE TABLE empreendedor (
    id_empreendedor INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL,
    CONSTRAINT pk_empreendedor PRIMARY KEY (id_empreendedor),
    CONSTRAINT uq_empreendedor_nome UNIQUE (nome)
);

CREATE TABLE regiao_hidrografica (
    id_regiao_hidrografica INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL,
    CONSTRAINT pk_regiao_hidrografica PRIMARY KEY (id_regiao_hidrografica),
    CONSTRAINT uq_regiao_hidrografica_nome UNIQUE (nome)
);

CREATE TABLE comite_federal (
    id_comite_federal INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL,
    CONSTRAINT pk_comite_federal PRIMARY KEY (id_comite_federal),
    CONSTRAINT uq_comite_federal_nome UNIQUE (nome)
);

CREATE TABLE comite_estadual (
    id_comite_estadual INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL,
    CONSTRAINT pk_comite_estadual PRIMARY KEY (id_comite_estadual),
    CONSTRAINT uq_comite_estadual_nome UNIQUE (nome)
);

CREATE TABLE unidade_gestao (
    id_unidade_gestao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL,
    CONSTRAINT pk_unidade_gestao PRIMARY KEY (id_unidade_gestao),
    CONSTRAINT uq_unidade_gestao_nome UNIQUE (nome)
);

CREATE TABLE barragem (
    cod_snisb TEXT NOT NULL,
    cod_fiscalizador TEXT NOT NULL,
    nome TEXT NOT NULL,
    altura_fundacao_m NUMERIC NOT NULL,
    altura_terreno_m NUMERIC,
    capacidade_reservatorio_texto TEXT NOT NULL,
    capacidade_reservatorio_padronizada NUMERIC,
    data_cadastro DATE NOT NULL,
    tipo_material TEXT,
    uso_principal TEXT NOT NULL,
    latitude NUMERIC NOT NULL,
    longitude NUMERIC NOT NULL,
    regulada_pnsb BOOLEAN NOT NULL,
    id_empreendedor INTEGER NOT NULL,
    id_municipio INTEGER NOT NULL,
    fase_vida TEXT,
    orgao_fiscalizador TEXT NOT NULL,
    numero_autorizacao TEXT NOT NULL,
    data_autorizacao DATE,
    id_regiao_hidrografica INTEGER NOT NULL,
    cod_trecho_curso_dagua TEXT,
    curso_dagua TEXT NOT NULL,
    dominio_curso_dagua TEXT,
    id_comite_federal INTEGER,
    id_comite_estadual INTEGER,
    id_unidade_gestao INTEGER,
    possui_pae BOOLEAN,
    possui_plano_seguranca BOOLEAN NOT NULL,
    possui_revisao_periodica BOOLEAN NOT NULL,
    categoria_risco TEXT NOT NULL,
    dano_potencial_associado TEXT NOT NULL,
    barragem_autuada BOOLEAN NOT NULL,
    completude_cadastro TEXT NOT NULL,
    CONSTRAINT pk_barragem PRIMARY KEY (cod_snisb),
    CONSTRAINT fk_barragem_empreendedor FOREIGN KEY (id_empreendedor)
        REFERENCES empreendedor (id_empreendedor),
    CONSTRAINT fk_barragem_municipio FOREIGN KEY (id_municipio)
        REFERENCES municipio (id_municipio),
    CONSTRAINT fk_barragem_regiao_hidrografica FOREIGN KEY (id_regiao_hidrografica)
        REFERENCES regiao_hidrografica (id_regiao_hidrografica),
    CONSTRAINT fk_barragem_comite_federal FOREIGN KEY (id_comite_federal)
        REFERENCES comite_federal (id_comite_federal),
    CONSTRAINT fk_barragem_comite_estadual FOREIGN KEY (id_comite_estadual)
        REFERENCES comite_estadual (id_comite_estadual),
    CONSTRAINT fk_barragem_unidade_gestao FOREIGN KEY (id_unidade_gestao)
        REFERENCES unidade_gestao (id_unidade_gestao),
    CONSTRAINT ck_barragem_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_barragem_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE registro_origem (
    id_registro INTEGER GENERATED BY DEFAULT AS IDENTITY,
    numero_linha INTEGER NOT NULL,
    cod_snisb TEXT NOT NULL,
    CONSTRAINT pk_registro_origem PRIMARY KEY (id_registro),
    CONSTRAINT uq_registro_origem_numero_linha UNIQUE (numero_linha),
    CONSTRAINT uq_registro_origem_cod_snisb UNIQUE (cod_snisb),
    CONSTRAINT fk_registro_origem_barragem FOREIGN KEY (cod_snisb)
        REFERENCES barragem (cod_snisb)
);

CREATE TABLE campo_origem (
    ordem_coluna INTEGER NOT NULL,
    nome_original TEXT NOT NULL,
    CONSTRAINT pk_campo_origem PRIMARY KEY (ordem_coluna),
    CONSTRAINT uq_campo_origem_nome_original UNIQUE (nome_original)
);

CREATE TABLE valor_origem (
    id_registro INTEGER NOT NULL,
    ordem_coluna INTEGER NOT NULL,
    valor_original TEXT NOT NULL,
    CONSTRAINT pk_valor_origem PRIMARY KEY (id_registro, ordem_coluna),
    CONSTRAINT fk_valor_origem_registro FOREIGN KEY (id_registro)
        REFERENCES registro_origem (id_registro),
    CONSTRAINT fk_valor_origem_campo FOREIGN KEY (ordem_coluna)
        REFERENCES campo_origem (ordem_coluna)
);

-- Índices adicionais para as colunas de chave estrangeira consultadas por JOIN.
CREATE INDEX idx_barragem_id_empreendedor ON barragem (id_empreendedor);
CREATE INDEX idx_barragem_id_municipio ON barragem (id_municipio);
CREATE INDEX idx_barragem_id_regiao_hidrografica ON barragem (id_regiao_hidrografica);
CREATE INDEX idx_barragem_id_comite_federal ON barragem (id_comite_federal);
CREATE INDEX idx_barragem_id_comite_estadual ON barragem (id_comite_estadual);
CREATE INDEX idx_barragem_id_unidade_gestao ON barragem (id_unidade_gestao);
CREATE INDEX idx_valor_origem_ordem_coluna ON valor_origem (ordem_coluna);

COMMIT;
